#!/usr/bin/env python3
"""Regenerate the generated documentation.

``docs/protocol_reference.md`` is produced by the CLI itself (``wider protocol explain --markdown``) on a fresh
temporary project, so the file shows exactly what a researcher sees and the defaults are the original review's
values. The text of every row comes from the ``Field(description=...)`` of ``wider.core.protocol.ReviewProtocol``:
edit the descriptions there, then run ``python scripts/build_docs.py``.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "docs" / "protocol_reference.md"
HEADER = "<!-- Generated by scripts/build_docs.py from wider/core/protocol.py; edit the Field descriptions, not this file. -->\n"


def build_protocol_reference(out: Path = REFERENCE) -> Path:
    """Run ``wider init`` and ``wider protocol explain --markdown`` in a temporary directory and write ``out``."""
    with tempfile.TemporaryDirectory() as tmp:
        proj = Path(tmp) / "reference_project"
        subprocess.run([sys.executable, "-m", "wider", "init", str(proj)], check=True, cwd=ROOT, capture_output=True)
        md = subprocess.run([sys.executable, "-m", "wider", "protocol", "explain", "--markdown", "--dir", str(proj)],
                            check=True, cwd=ROOT, capture_output=True, text=True).stdout
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(HEADER + md.rstrip("\n") + "\n", encoding="utf-8")
    return out


def main() -> None:
    out = build_protocol_reference()
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
