"""Hand-written SVG plots for the query refinement loop (vision change 2a, D7).

Each plot carries a ``<title>`` and a ``<desc>`` that lists its numbers in words, and the page and the CLI show a text
table with the same numbers next to it, so nothing is told by colour or position alone. No plotting library: the SVG
text stays readable and diffable in the run folder.
"""
from __future__ import annotations

from xml.sax.saxutils import escape

_CELL = 22
_FILL = {"hit": "#2a6f97", "uncertain": "#f2c14e", "": "#ffffff"}
_MARK = {"hit": "x", "uncertain": "?", "": ""}
_WORD = {"hit": "hit", "uncertain": "uncertain", "": "no match"}


def _esc(s) -> str:
    return escape(str(s), {'"': "&quot;"})


def heatmap(grids: dict[str, dict]) -> str:
    """The term-by-seed grid of :func:`wider.search.diagnostics.grid`, one section per platform: a row per term
    (block: term), a column per development seed, a filled cell marked ``x`` for a hit and ``?`` for uncertain."""
    desc: list[str] = []
    for plat, g in grids.items():
        for r in g["rows"]:
            hit = [s for s, c in zip(g["seeds"], r["cells"], strict=True) if c == "hit"]
            unc = [s for s, c in zip(g["seeds"], r["cells"], strict=True) if c == "uncertain"]
            line = f"{plat}, {r['block']}: {r['term']}: hits {', '.join(hit) or 'no seed'}"
            desc.append(line + (f"; uncertain {', '.join(unc)}" if unc else ""))
    label_w = max([len(f"{r['block']}: {r['term']}") for g in grids.values() for r in g["rows"]] + [10]) * 7 + 20
    ncol = max([len(g["seeds"]) for g in grids.values()] + [1])
    W = max(label_w + ncol * _CELL + 20, 640)   # wide enough for the legend line
    body: list[str] = []
    y = 20
    for plat, g in grids.items():
        body.append(f'<text x="10" y="{y + 14}" font-weight="bold">{_esc(plat)}</text>')
        y += 24
        for j, s in enumerate(g["seeds"]):
            x = label_w + j * _CELL + _CELL / 2
            body.append(f'<text x="{x}" y="{y + 40}" transform="rotate(-60 {x} {y + 40})" font-size="11">{_esc(s)}</text>')
        y += 48
        if not g["seeds"]:
            body.append(f'<text x="10" y="{y}" fill="#555">no development seed paper</text>')
            y += 20
        for r in g["rows"]:
            body.append(f'<text x="10" y="{y + 15}" font-size="12">{_esc(r["block"] + ": " + r["term"])}</text>')
            for j, (s, c) in enumerate(zip(g["seeds"], r["cells"], strict=True)):
                x = label_w + j * _CELL
                body.append("<g><title>" + _esc(r["term"] + " on " + s + ": " + _WORD[c]) + "</title>"
                            f'<rect x="{x}" y="{y}" width="{_CELL - 2}" height="{_CELL - 2}" fill="{_FILL[c]}" '
                            f'stroke="#888"/>' + (f'<text x="{x + (_CELL - 2) / 2}" y="{y + 15}" text-anchor="middle" '
                                                  f'font-size="12" fill="{"#fff" if c == "hit" else "#111"}">'
                                                  f'{_MARK[c]}</text>' if c else "") + "</g>")
            y += _CELL
        y += 16
    H = y + 24
    body.append(f'<text x="10" y="{H - 8}" font-size="11" fill="#555">x hit, ? uncertain (the profile cannot decide), '
                'empty no match. Generated by WIDER from a dry run on the seed papers.</text>')
    head = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
            'font-family="Helvetica, Arial, sans-serif" font-size="13" role="img">',
            "<title>Terms against development seed papers</title>",
            f"<desc>{_esc('. '.join(desc) or 'No terms.')}</desc>",
            f'<rect width="{W}" height="{H}" fill="#ffffff"/>']
    return "\n".join(head + body + ["</svg>"])


def name_map(m: dict) -> str:
    """The name map of :func:`wider.seeds.names.name_map`: one row per group of names that denote the same
    construct, then the look-alikes, each named in words in ``<desc>`` too."""
    lines = [("Same construct: " + ", ".join(g), "#2a6f97") for g in m["groups"] if len(g) > 1]
    lines += [(f"Look-alike: {x['name']} (a different construct from {x['of']})", "#9a3412") for x in m["look_alikes"]]
    if not lines:
        lines = [("No names grouped yet.", "#555555")]
    W = max([len(t) for t, _ in lines] + [40]) * 7 + 40
    body, y = [], 24
    for text, colour in lines:
        body.append(f'<text x="14" y="{y}" fill="{colour}">{_esc(text)}</text>')
        y += 22
    H = y + 18
    body.append(f'<text x="14" y="{H - 8}" font-size="11" fill="#555">From "also called" sentences in the seed papers '
                "and your same-construct answers. Generated by WIDER.</text>")
    head = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
            'font-family="Helvetica, Arial, sans-serif" font-size="13" role="img">',
            "<title>Name map of the seed papers</title>",
            f"<desc>{_esc('. '.join(t for t, _ in lines))}</desc>",
            f'<rect width="{W}" height="{H}" fill="#ffffff"/>']
    return "\n".join(head + body + ["</svg>"])


